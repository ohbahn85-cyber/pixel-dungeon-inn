export function getCurrentInnLevel(reputationOrRank: number, isExplicitRank = false): InnLevelDef {
  if (isExplicitRank) {
    return INN_LEVELS.find((l) => l.level === reputationOrRank) ?? INN_LEVELS[0];
  }
  let current = INN_LEVELS[0];
  for (const lvl of INN_LEVELS) {
    if (reputationOrRank >= lvl.requiredRep) {
      current = lvl;
    } else {
      break;
    }
  }
  return current;
}

export function getNextInnLevel(currentRankLevel: number, isExplicitRank = false): InnLevelDef | null {
  if (isExplicitRank) {
    return INN_LEVELS.find((l) => l.level === currentRankLevel + 1) ?? null;
  }
  for (const lvl of INN_LEVELS) {
    if (currentRankLevel < lvl.requiredRep) {
      return lvl;
    }
  }
  return null;
}
