export function getUpgradeCost(def: UpgradeDef, currentLevel: number): number {
  return Math.floor(def.baseCost * Math.pow(def.costScale, currentLevel));
}

export function getCurrentInnLevel(reputation: number): InnLevelDef {
  let current = INN_LEVELS[0];
  for (const lvl of INN_LEVELS) {
    if (reputation >= lvl.requiredRep) {
      current = lvl;
    } else {
      break;
    }
  }
  return current;
}

export function getNextInnLevel(reputation: number): InnLevelDef | null {
  for (const lvl of INN_LEVELS) {
    if (reputation < lvl.requiredRep) {
      return lvl;
    }
  }
  return null;
}
