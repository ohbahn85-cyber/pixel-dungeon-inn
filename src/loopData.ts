// 9. +강화 확률 곡선 (+0→+1 95% ~ +9→+10 2.0% ~ +14→+15 0.20%, 실패 시 완전 파괴)
// ============================================================================
export const BASE_ENHANCE_RATES: number[] = [
  0.95, // +0 -> +1 (95.0%)
  0.85, // +1 -> +2 (85.0%)
  0.72, // +2 -> +3 (72.0%)
  0.58, // +3 -> +4 (58.0%)
  0.42, // +4 -> +5 (42.0%)
  0.28, // +5 -> +6 (28.0%)
  0.16, // +6 -> +7 (16.0%)
  0.09, // +7 -> +8 (9.0%)
  0.045, // +8 -> +9 (4.5%)
  0.02, // +9 -> +10 (2.0% - 목표 1~3%)
  0.012, // +10 -> +11 (1.2%)
  0.008, // +11 -> +12 (0.8%)
  0.005, // +12 -> +13 (0.5%)
  0.0035, // +13 -> +14 (0.35%)
  0.002, // +14 -> +15 (0.20% - 1% 크게 미만)
];

export const MAX_ENHANCE_LEVEL = 15;

/**
 * 현재 +강화 수치(currentPlus)에서 다음 단계로 갈 때의 성공 확률 계산
 * 숫돌(smith_grindstone) 및 드워프 산맥 출신 보너스는 비례 배율로만 소폭 적용되어
 * 고강(+10 이상)이 절대 흔해지지 않도록 엄격히 제한합니다.
 */
export function getEnhanceSuccessRate(
  currentPlus: number,
  grindstoneLevel: number,
  hasDwarfOriginBonus = false
): number {
  if (currentPlus < 0 || currentPlus >= MAX_ENHANCE_LEVEL) return 0;
  const base = BASE_ENHANCE_RATES[currentPlus] ?? 0.001;
  // 비례 보정: 숫돌 레벨당 상대 확률 +2%, 드워프 출신 +3% (예: 2.0% -> 최대 ~2.38%)
  const relBonus = 1 + grindstoneLevel * 0.02 + (hasDwarfOriginBonus ? 0.03 : 0);
  const maxCap = currentPlus === 0 ? 0.98 : currentPlus >= 9 ? base * 1.25 : Math.min(0.95, base * 1.18);
  return Math.min(maxCap, base * relBonus);
}

/**
 * +강화 레벨에 따른 장비 능력치 배율
 * +1: 1.18배, +2: 1.38배, +3: 1.62배 ... +7: 3.1배, +10: 5.2배, +15: 10.5배
 */
export function getEnhanceStatMultiplier(enhanceLevel: number): number {
  if (enhanceLevel <= 0) return 1.0;
  return 1 + enhanceLevel * 0.16 + Math.pow(enhanceLevel, 1.55) * 0.04;
}

/**
 * +강화 시도 비용 (골드 및 재료)
 */
export function getEnhanceCost(
  def: EquipmentDef,
  currentPlus: number
): { gold: number; materials: Record<string, number> } {
  const rarityBaseGold: Record<RarityTier, number> = {
    common: 12,
    uncommon: 22,
    rare: 48,
    epic: 95,
    legendary: 180,
  };
  const baseG = rarityBaseGold[def.rarity] ?? 20;
  const gold = Math.floor(baseG * Math.pow(1.38, currentPlus));

  const matCount = Math.max(1, Math.min(5, 1 + Math.floor(currentPlus / 3)));
  const materials: Record<string, number> = {};
  if (def.rarity === 'common' || def.rarity === 'uncommon') {
    materials['mat_iron_scrap'] = matCount;
  } else if (def.rarity === 'rare') {
    materials['mat_mana_crystal'] = matCount;
  } else if (def.rarity === 'epic') {
    materials['mat_mithril_ore'] = matCount;
  } else {
    materials['mat_fire_coal'] = matCount;
  }
  return { gold, materials };
}

