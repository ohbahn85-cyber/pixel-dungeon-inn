"""Pack the summon body sheet and separate equipment sheet into game atlases."""

from argparse import ArgumentParser
from pathlib import Path

from PIL import Image

BODY_GRIPS = (
    ((139, 250), (528, 251), (915, 250), (1300, 246)),
    ((269, 517), (657, 517), (1048, 516), (1433, 516)),
    ((255, 904), (643, 903), (1038, 905), (1427, 905)),
)
GEAR_GRIPS = (
    ((181, 83), (442, 69), (692, 72), (962, 55)),
    ((169, 336), (434, 315), (698, 315), (956, 314)),
    ((132, 642), (382, 640), (643, 629), (900, 630)),
    ((129, 887), (386, 890), (644, 886), (892, 885)),
    ((167, 1148), (403, 1149), (675, 1139), (924, 1140)),
    ((154, 1407), (402, 1407), (658, 1397), (910, 1394)),
)
BODY_ROWS = (0, 338, 676, 1016)
GEAR_ROWS = (0, 263, 507, 764, 1016, 1273, 1536)


def pack(source, rows, grips, cell_width, cell_height, baseline, art_height):
    if source.height != rows[-1]:
        raise ValueError(f"Expected a sheet {rows[-1]} pixels high, got {source.height}")
    atlas = Image.new("RGBA", (4 * cell_width, len(grips) * cell_height))
    pivots = []
    mask = source.getchannel("A").point(lambda alpha: 255 if alpha >= 112 else 0)
    for row, points in enumerate(grips):
        for col, (grip_x, grip_y) in enumerate(points):
            left = source.width * col // 4
            top = rows[row]
            bounds = (left, top, source.width * (col + 1) // 4, rows[row + 1])
            crop = mask.crop(bounds).getbbox()
            if crop is None:
                raise ValueError(f"Empty cell at row {row + 1}, column {col + 1}")
            sprite = source.crop(bounds).crop(crop)
            scale = art_height / sprite.height
            width = round(sprite.width * scale)
            if width > cell_width:
                raise ValueError(f"Sprite too wide at row {row + 1}, column {col + 1}")
            alpha = sprite.getchannel("A").point(lambda value: min(255, max(0, (value - 30) * 255 // 163)))
            sprite.putalpha(alpha)
            sprite = sprite.resize((width, art_height), Image.Resampling.BOX)
            x = (cell_width - width) // 2
            y = baseline - art_height
            atlas.paste(sprite, (col * cell_width + x, row * cell_height + y))
            pivots.append((round(x + (grip_x - left - crop[0]) * scale),
                           round(y + (grip_y - top - crop[1]) * scale)))
    return atlas, pivots


def write_pivots(body, gear, destination):
    lines = ["-- Generated by scripts/import_summon_ranks.py", "return {"]
    for name, points in (("body", body), ("gear", gear)):
        lines.append(f"    {name} = {{")
        for x, y in points:
            lines.append(f"        {{ {x}, {y} }},")
        lines.append("    },")
    lines.append("}")
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("bodies", type=Path)
    parser.add_argument("equipment", type=Path)
    args = parser.parse_args()
    assets = Path(__file__).resolve().parents[1] / "game/assets"
    with Image.open(args.bodies) as image:
        bodies, body_pivots = pack(image.convert("RGBA"), BODY_ROWS, BODY_GRIPS, 128, 112, 104, 96)
    with Image.open(args.equipment) as image:
        gear, gear_pivots = pack(image.convert("RGBA"), GEAR_ROWS, GEAR_GRIPS, 96, 96, 88, 80)
    bodies.save(assets / "summon_ranks.png")
    gear.save(assets / "summon_gear.png")
    write_pivots(body_pivots, gear_pivots, assets / "summon_pivots.lua")
