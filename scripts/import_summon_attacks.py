"""Pack combat body poses and preserve weapon grips across sword silhouette edits."""

from argparse import ArgumentParser
from pathlib import Path

from PIL import Image

CELL_WIDTH, CELL_HEIGHT = 128, 112
ROOT_X, GROUND_Y, BODY_HEIGHT = 64, 104, 96

# Source artwork coordinates relative to each original grid cell.
# The first two values are the visual root and weapon grip. Bow frames also mark the string hand.
SWORD = (
    (154, (94, 209)),
    (172, (99, 74)),
    (141, (274, 143)),
    (157, (234, 225)),
)
ARCHER = (
    (148, (205, 201), (121, 214)),
    (150, (229, 136), (143, 146)),
    (165, (244, 136), (105, 123)),
    (178, (257, 135), (61, 130)),
)
RECOVERY = (
    ((211, (127, 264)), (211, (125, 266)), (219, (152, 263)), (222, (151, 270))),
    ((223, (337, 259), (164, 251)), (222, (335, 260), (166, 250)),
     (223, (336, 259), (169, 253)), (225, (338, 261), (170, 253))),
)
REVISED_GRIPS = ((466, 330), (407, 456))


def cell(sheet, row, col, rows):
    width, height = sheet.size
    return sheet.crop((width * col // 4, height * row // rows,
                       width * (col + 1) // 4, height * (row + 1) // rows))


def bounds(sprite):
    mask = sprite.getchannel("A").point(lambda value: 255 if value >= 144 else 0)
    return mask.getbbox()


def place(atlas, sprite, frame, row, scale, root, grip, draw_hand=None):
    left, top, right, bottom = bounds(sprite)
    art = sprite.crop((left, top, right, bottom))
    art.putalpha(art.getchannel("A").point(lambda value: min(255, max(0, (value - 30) * 255 // 163))))
    width, height = round(art.width * scale), round(art.height * scale)
    x, y = ROOT_X + round((left - root) * scale), GROUND_Y - height
    if x < 0 or y < 0 or x + width > CELL_WIDTH:
        raise ValueError(f"Attack pose at row {row + 1}, frame {frame + 1} exceeds its atlas cell")
    atlas.paste(art.resize((width, height), Image.Resampling.BOX),
                (frame * CELL_WIDTH + x, row * CELL_HEIGHT + y))
    points = grip if draw_hand is None else (*grip, *draw_hand)
    return tuple(round(offset + ((value - start) * scale)) for value, (offset, start) in
                 zip(points, ((x, left), (y, top), (x, left), (y, top))))


def fit_sword_edit(original, edited, scale, root, original_grip, edited_grip):
    left, top, _, bottom = bounds(original)
    grip_x = ROOT_X + round((left - root) * scale) + round((original_grip[0] - left) * scale)
    new_left, new_top, _, new_bottom = bounds(edited)
    new_scale = round((bottom - top) * scale) / (new_bottom - new_top)
    grip_offset = round((edited_grip[0] - new_left) * new_scale)
    new_root = new_left + (ROOT_X + grip_offset - grip_x) / new_scale
    return new_scale, new_root


def pack(sword, archer, recovery, contact, follow_through, output):
    atlas = Image.new("RGBA", (CELL_WIDTH * 5, CELL_HEIGHT * 8))
    anchors = []
    revised_sword = {2: (contact, REVISED_GRIPS[0]), 3: (follow_through, REVISED_GRIPS[1])}
    for family, (sheet, poses) in enumerate(((sword, SWORD), (archer, ARCHER))):
        for rank in range(4):
            row = family * 4 + rank
            _, top, _, bottom = bounds(cell(sheet, rank, 0, 4))
            scale = BODY_HEIGHT / (bottom - top)
            points = []
            for frame, pose in enumerate(poses):
                original = cell(sheet, rank, frame, 4)
                if family == 0 and frame in revised_sword:
                    strip, grip = revised_sword[frame]
                    edited = cell(strip, 0, rank, 1)
                    edit_scale, root = fit_sword_edit(original, edited, scale, *pose, grip)
                    points.append(place(atlas, edited, frame, row, edit_scale, root, grip))
                else:
                    points.append(place(atlas, original, frame, row, scale, *pose))
            change = cell(recovery, family, rank, 2)
            _, top, _, bottom = bounds(change)
            points.append(place(atlas, change, 4, row, BODY_HEIGHT / (bottom - top + 10), *RECOVERY[family][rank]))
            anchors.append(points)

    atlas.save(output / "summon_attack_poses.png")
    rows = [", ".join("{" + ", ".join(str(value) for value in pose) + "}" for pose in row) for row in anchors]
    table = "\n".join("    {" + row + "}," for row in rows)
    (output / "summon_attack_anchors.lua").write_text(
        "-- Generated by scripts/import_summon_attacks.py\nreturn {\n" + table + "\n}\n", encoding="utf-8")


if __name__ == "__main__":
    cli = ArgumentParser(description=__doc__)
    sheets = ("sword", "archer", "recovery", "contact", "follow_through")
    for name in sheets:
        cli.add_argument(name, type=Path)
    args = cli.parse_args()
    inputs = []
    for name in sheets:
        with Image.open(getattr(args, name)) as image:
            inputs.append(image.convert("RGBA"))
    pack(*inputs, Path(__file__).resolve().parents[1] / "game/assets")
